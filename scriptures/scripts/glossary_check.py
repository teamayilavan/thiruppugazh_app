"""Check the Tamil glossary (tamil/GLOSSARY.md) against the story texts and the app's Tamil text.

For every row: how often its English names occur in pdf/narratives/*.txt, and how often its Tamil form and the
"also seen" forms occur in the app's song meanings (pathavurai) and lyrics (assets/thiruppugazh.db). Tamil forms are
matched by stem (a final virama is dropped, so ராமன் also counts ராமனை, ராமனின்). Also lists capitalised names in the
narratives that no row covers, and rows whose English never occurs.

Writes tamil/glossary-report.md. Read-only on everything else.
Run: python3 -I -X utf8 scriptures/scripts/glossary_check.py
"""
import collections
import glob
import json
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GLOSSARY = ROOT / "tamil" / "GLOSSARY.md"
REPORT = ROOT / "tamil" / "glossary-report.md"
NARR = ROOT / "pdf" / "narratives"
DB = ROOT.parent / "assets" / "thiruppugazh.db"

VIRAMA = "்"
TAMIL_LETTER = "[஀-௿]"
# Words that start a sentence or are generic titles; not names on their own.
STOP = set("""The A An In At On For From To By With After Before When Then This That These Those It He She They We You His Her
Its Their There Here What Who Which Where How As If But And Or Nor So Yet Some Many Each Every Both One Two Twelve No Not
Unlike Among During Later Afterwards Once Another Let Have Seeking Receive Come Carry Stop Remain Run Seen Beneath High
King Queen Lord Goddess Mother Father Mount Lady Great Supreme Sri Glory Roar Light Speech Earth Sea Sun Time Death Gods
God Feet Crown Boat Milk Ocean Song Puranic South North India English Amme Monday""".split())


def parse_glossary():
    rows, section = [], ""
    for line in GLOSSARY.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
            continue
        if not line.startswith("| ") or line.startswith("| English") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 5:
            continue
        en, variants, ta, alts, note = cells[:5]
        rows.append(dict(
            section=section, en=en,
            names=[en] + [v.strip() for v in variants.split(";") if v.strip()],
            ta=ta, alts=[a.strip() for a in alts.split(";") if a.strip()], note=note))
    return rows


def stem(form):
    words = form.split()
    if words and words[-1].endswith(VIRAMA):
        words[-1] = words[-1][:-1]
    return " ".join(words)


def ta_count(text, form):
    """Occurrences of the form's stem at the start of a word (so மால் does not count inside திருமால்)."""
    return len(re.findall("(?<!" + TAMIL_LETTER + ")" + re.escape(stem(form)), text))


def norm(name):
    return re.sub(r"[^a-z]", "", name.lower())


def en_count(text, name):
    flags = 0 if name[:1].isupper() else re.IGNORECASE
    return len(re.findall(r"(?<![A-Za-z])" + re.escape(name) + r"(?![a-z])", text, flags))


def load_tamil():
    con = sqlite3.connect(DB)
    meanings, lyrics = [], []
    for patha, mean, lyr in con.execute("select pathavurai, meanings, lyrics_list from songs"):
        if patha and patha.strip():
            meanings.append(patha)
        elif mean:
            meanings.extend(json.loads(mean))
        if lyr:
            lyrics.extend(json.loads(lyr))
    venues = collections.defaultdict(collections.Counter)
    for en, ta in con.execute("select english_venue, place from songs"):
        if en and ta:
            venues[norm(en)][ta.replace("\xa0", " ").strip()] += 1
    return "\n".join(meanings), "\n".join(lyrics), venues


def main():
    rows = parse_glossary()
    narr = "\n".join(Path(f).read_text(encoding="utf-8") for f in sorted(glob.glob(str(NARR / "*.txt"))))
    meaning, lyric, venues = load_tamil()

    out = ["# Glossary report (generated by `scripts/glossary_check.py`; do not edit)", "",
           f"{len(rows)} glossary rows. English counts are over the {len(glob.glob(str(NARR / '*.txt')))} narratives; "
           "Tamil counts are stem matches in the app's song meanings (M) and lyrics (L).", ""]

    flagged, unused = [], []
    table = []
    for r in rows:
        n = sum(en_count(narr, x) for x in r["names"])
        m, l = ta_count(meaning, r["ta"]), ta_count(lyric, r["ta"])
        alts = []
        for a in r["alts"]:
            am, al = ta_count(meaning, a), ta_count(lyric, a)
            alts.append(f"{a} {am}/{al}")
            if am + al > 2 * (m + l) and am + al >= 5 and "kept on purpose" not in r["note"]:
                flagged.append((r, a, m + l, am + al))
        if n == 0:
            unused.append(r)
        table.append(f"| {r['section']} | {r['en']} | {n} | {r['ta']} | {m}/{l} | {'; '.join(alts)} |")

    place_diff = []
    for r in rows:
        for x in r["names"]:
            if norm(x) in venues and r["ta"] not in venues[norm(x)]:
                place_diff.append((r, x, ", ".join(f"{t} ({c})" for t, c in venues[norm(x)].most_common())))
    out += ["## Place names that differ from the app", "",
            "The English name is a song venue in the app, whose Tamil `place` differs from the glossary form. "
            "The books print the app's place under each song, so prefer the app's form unless there is a reason.", "",
            "| English | Glossary | App place (songs) |", "|---|---|---|"]
    out += [f"| {x} | {r['ta']} | {d} |" for r, x, d in place_diff] or ["| none | | |"]
    out += ["", "## Tamil form less attested than an alternative", "",
            "The chosen form occurs much less in the meanings and lyrics than one of its \"also seen\" forms. "
            "Not necessarily wrong (simple modern prose may differ from the old meanings), but decide on purpose.", "",
            "| English | Chosen | M+L | Alternative | M+L |", "|---|---|---|---|---|"]
    out += [f"| {r['en']} | {r['ta']} | {a} | {b} | {c} |" for r, b, a, c in
            [(r, a, x, y) for r, a, x, y in flagged]] or ["| none | | | | |"]

    covered = set(venues)
    for r in rows:
        for x in r["names"]:
            covered.add(x)
            covered.update(w for w in re.split(r"[ -]", x) if w)
    cand = collections.Counter(
        m for m in re.findall(r"(?<![.!?]\s)\b[A-Z][a-z]+(?:[- ][A-Z][a-z]+)*", narr))
    missing = []
    for phrase, c in cand.most_common():
        words = [w for w in re.split(r"[ -]", phrase) if w not in STOP]
        if not words or phrase in covered or norm(phrase) in covered or all(
                w in covered or norm(w) in covered for w in words):
            continue
        # Padalam titles and similar are written from the Tamil original, not glossed one by one.
        if re.search(r"\b(Padalam|Puranam|Parva|Kandam|Kanda|Sargam)\b", phrase) and c < 5:
            continue
        missing.append((phrase, c))

    out += ["", f"## Names in the narratives not covered ({len(missing)})", "",
            "Capitalised words or phrases in the narratives with no glossary row (sentence starters and generic titles "
            "ignored; rare padalam and Puranam titles skipped, since those are written from the Tamil original).", "",
            ", ".join(f"{p} ({c})" for p, c in missing) or "none"]

    out += ["", f"## Rows whose English never occurs in the narratives ({len(unused)})", "",
            ", ".join(r["en"] for r in unused) or "none"]

    out += ["", "## All rows", "", "| Section | English | In narratives | Tamil | M/L | Also seen M/L |",
            "|---|---|---|---|---|---|"] + table
    # Tamil texts: an "also seen" form used where the glossary chose another. Skipped when the alternative is a
    # prefix of the chosen form (திருமால் / மால்) or the note says the alternative has a permitted use.
    ta_files = sorted(glob.glob(str(ROOT / "pdf" / "narratives-ta" / "*.txt")))
    misuse = []
    for f in ta_files:
        text = Path(f).read_text(encoding="utf-8")
        for r in rows:
            for a in r["alts"]:
                if stem(r["ta"]).startswith(stem(a)) or stem(a).startswith(stem(r["ta"])) or a in r["note"]:
                    continue
                n = ta_count(text, a)
                if n:
                    misuse.append(f"| {Path(f).stem} | {a} ({n}) | {r['ta']} | {r['en']} |")
    # Tamil texts against their English: same paragraphs and the same numbers (verses, songs, chapters).
    parity = []
    for f in ta_files:
        en_file = NARR / Path(f).name
        if not en_file.exists():
            parity.append(f"| {Path(f).stem} | no English file | |")
            continue
        en_text, ta_text = en_file.read_text(encoding="utf-8"), Path(f).read_text(encoding="utf-8")
        paras = lambda t: len([p for p in re.split(r"\n\s*\n", t.strip()) if p.strip()])
        nums = lambda t: collections.Counter(re.findall(r"\d+(?:[.,]\d+)*", t))
        if paras(en_text) != paras(ta_text):
            parity.append(f"| {Path(f).stem} | paragraphs: English {paras(en_text)}, Tamil {paras(ta_text)} | |")
        ne, nt = nums(en_text), nums(ta_text)
        if ne != nt:
            parity.append(f"| {Path(f).stem} | numbers differ | only English: {' '.join((ne - nt).elements()) or '-'}; "
                          f"only Tamil: {' '.join((nt - ne).elements()) or '-'} |")
    out += ["", f"## Tamil texts against the English ({len(parity)})", "",
            "Each Tamil story should have the English story's paragraphs and exactly its numbers.", "",
            "| Story | Problem | Detail |", "|---|---|---|"] + (parity or ["| none | | |"])
    out += ["", f"## Tamil texts: forms the glossary does not choose ({len(misuse)})", "",
            f"Over the {len(ta_files)} files in `pdf/narratives-ta/`. Fix the text, or note in the glossary why the "
            "form is right there (a note that names the form silences it).", "",
            "| Story | Form used | Glossary form | English |", "|---|---|---|---|"] + (misuse or ["| none | | | |"])
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rows)} rows; {len(flagged)} less attested than an alternative; "
          f"{len(place_diff)} places differ from the app; {len(missing)} names not covered; {len(unused)} rows unused -> {REPORT.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
