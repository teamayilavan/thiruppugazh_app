"""Build vishnu/avatar-episodes.md and vishnu/avatar-verses.md from avatar_episodes.py.

Checks (fails on any miss): every Bhagavata verse number is on the vedabase chapter page; every Valmiki shloka number
exists on the sarga page; every Kamba verse number exists in the Wikisource padalam (and is quoted); every Vishnu Purana
chapter page contains its keyword.
Run:  python -I scriptures/scripts/build_avatar_verses.py   (network needed the first time; caches in scripts/.cache)
"""
import html
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.stdout.reconfigure(encoding="utf-8")
from avatar_episodes import A_, E  # noqa: E402
from fetch_krishna import CACHE, _get, sb  # noqa: E402
from fetch_sources import valmiki_verses  # noqa: E402
from find_kamba import verses as kverses  # noqa: E402

V = Path(__file__).resolve().parent.parent / "vishnu"
hits = {str(h["song"]): h for h in json.loads((V / "shortlist.json").read_text(encoding="utf-8"))}

_sb, _val, _kam = {}, {}, {}


def sb_has(c, ch, n):
    if (c, ch) not in _sb:
        cov = set()
        for lab, _ in sb(c, ch):
            lo, _, hi = lab.replace("–", "-").partition("-")
            cov.update(range(int(lo), int(hi or lo) + 1))
        _sb[(c, ch)] = cov
    return n in _sb[(c, ch)]


def val_has(k, s, n):
    if (k, s) not in _val:
        _val[(k, s)] = {x for x, _ in valmiki_verses(k, s)}
    return n in _val[(k, s)]


def kam(kandam, pad, n):
    if (kandam, pad) not in _kam:
        _kam[(kandam, pad)] = {num: t for num, _, t in kverses(kandam, pad)}
    t = _kam[(kandam, pad)].get(str(n))
    if t is None:
        sys.exit(f"Kamba verse not found: {pad} {n}")
    return t


def vp_ok(doc, kw):
    CACHE.mkdir(exist_ok=True)
    f = CACHE / f"vp_{doc}.txt"
    if not f.exists():
        raw = _get(f"https://www.wisdomlib.org/hinduism/book/vishnu-purana-wilson/d/doc{doc}.html")
        f.write_text(html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", raw))), encoding="utf-8")
    return re.search(kw, f.read_text(encoding="utf-8"), re.I) is not None


for eid, e in E.items():
    for c, ch, v, g in e["sb"]:
        lo, _, hi = v.partition("-")
        for n in range(int(lo), int(hi) + 1):
            if not sb_has(c, ch, n):
                sys.exit(f"Bhagavata verse missing: {c}.{ch}.{n} ({eid})")
    for k, s, nums, g in e["valmiki"]:
        for n in nums:
            if not val_has(k, s, n):
                sys.exit(f"Valmiki shloka missing: {k} {s}.{n} ({eid})")
    for kandam, pad, nums, g in e["kamba"]:
        for n in nums:
            kam(kandam, pad, n)
    for b, ch, doc, kw, g in e["vp"]:
        if not vp_ok(doc, kw):
            sys.exit(f"Vishnu Purana page lacks '{kw}': {b}.{ch} ({eid})")

KN = {"bala": "Bala"}


def span(nums):
    return ", ".join(map(str, nums))


out = [
    "# Avatar episodes: verse-level references",
    "",
    "Generated by `scripts/build_avatar_verses.py` from `scripts/avatar_episodes.py`. Do not hand-edit.",
    "",
    "Bhagavata = canto.chapter.verse (vedabase.io). Valmiki = sarga.shloka (valmikiramayan.net; Bala pages carry their own "
    "[1-sarga-shloka] tags). Kamba = padalam + verse, numbers restart in each padalam (Tamil Wikisource), quoted. "
    "Vishnu Purana = Wilson book.chapter on wisdomlib; the build checks the keyword is on the page but chapter-level only. "
    "Every number below was looked up and exists; the gists are mine.",
    "",
]
for eid, e in E.items():
    n = sum(1 for v in A_.values() if eid in v["eps"])
    out += [f"## {e['title']}  (`{eid}`, {n} songs)", ""]
    if e["sb"]:
        out += ["**Bhagavata Purana**", ""] + [f"- SB {c}.{ch}.{v}: {g}" for c, ch, v, g in e["sb"]] + [""]
    if e["valmiki"]:
        out += ["**Valmiki Ramayana**", ""] + [f"- {KN.get(k, k)} {s}.{span(nums)}: {g}" for k, s, nums, g in e["valmiki"]] + [""]
    if e["kamba"]:
        out += ["**Kamba Ramayanam**", ""]
        for kandam, pad, nums, g in e["kamba"]:
            out.append(f"- {pad.replace('_', ' ')} ({g})")
            for nn in nums:
                t = kam(kandam, pad, nn)
                out.append(f"    - {nn}: {t[:120]}{'…' if len(t) > 120 else ''}")
        out.append("")
    if e["vp"]:
        out += ["**Vishnu Purana (Wilson)**", ""] + [f"- {b}.{ch}: {g}" for b, ch, doc, kw, g in e["vp"]] + [""]
    if not (e["sb"] or e["valmiki"] or e["kamba"] or e["vp"]):
        out += ["No verse reference.", ""]
    if e["note"]:
        out += [f"Note: {e['note']}", ""]
    songs = sorted((s for s, v in A_.items() if eid in v["eps"]), key=int)
    out += ["Songs: " + (", ".join(songs) if songs else "none"), ""]
(V / "avatar-episodes.md").write_text("\n".join(out), encoding="utf-8")


def cell(e):
    parts = []
    if e["sb"]:
        parts.append("SB " + "; ".join(f"{c}.{ch}.{v}" for c, ch, v, g in e["sb"]))
    if e["valmiki"]:
        parts.append("Val " + "; ".join(f"{KN.get(k, k)} {s}.{span(nums)}" for k, s, nums, g in e["valmiki"]))
    if e["kamba"]:
        parts.append("Kamba " + "; ".join(f"{pad.replace('_', ' ')} {span(nums)}" for kandam, pad, nums, g in e["kamba"]))
    if e["vp"]:
        parts.append("VP " + "; ".join(f"{b}.{ch}" for b, ch, doc, kw, g in e["vp"]))
    return "<br>".join(parts) or "-"


rows = [
    "# Avatar songs: verse-level references",
    "",
    "Generated. See `avatar-episodes.md`. Conf h/m/l is the match between the song's line and the episode, not the numbers.",
    "",
    "| Song | Line (with previous line) | Episode(s) | References | Conf | Note |",
    "|---|---|---|---|---|---|",
]
for sid in sorted(A_, key=int):
    h, v = hits[sid], A_[sid]
    es = [E[x] for x in v["eps"]]
    rows.append(
        f"| {sid} {h['title']} | {h['prev_line']} / **{h['line']}** | " + ", ".join(e["title"] for e in es)
        + " | " + "<br><br>".join(f"**{e['title']}**: {cell(e)}" for e in es) + f" | {v['conf']} | {v['note']} |"
    )
(V / "avatar-verses.md").write_text("\n".join(rows) + "\n", encoding="utf-8")

smap = {}
for line in (V / "song-story-map.txt").read_text(encoding="utf-8").splitlines():
    if line.strip() and not line.startswith("#"):
        sid, slugs, _, _ = line.split("|")
        smap[sid] = slugs.split(",")
want = {"gajendra", "vamana", "narasimha", "samudra-manthana", "kurma", "varaha", "matsya", "vishnu-pralaya",
        "vishnu-brahma-origin", "vishnu-sleeping", "vishnu-temple-srirangam", "vishnu-temple-tirupati", "vishnu-temple-kanchi"}
need = {s for s, sl in smap.items() if want & set(sl)}
print(len(E), "episodes;", len(A_), "songs; avatar-slug songs without an episode:", sorted(need - set(A_), key=int))
