"""Build vishnu/krishna-episodes.md and vishnu/krishna-verses.md from krishna_episodes.py.

Checks: every Bhagavata verse number cited exists in the vedabase chapter page; every Mahabharata line reference
exists in the GRETIL Critical Edition text (and its Sanskrit is quoted). The build fails on any miss.
Run:  python -I scriptures/scripts/build_krishna_verses.py   (needs network the first time; caches in scripts/.cache)
"""
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.stdout.reconfigure(encoding="utf-8")
from fetch_krishna import mbh_lines, sb  # noqa: E402
from krishna_episodes import A_, E  # noqa: E402

V = Path(__file__).resolve().parent.parent / "vishnu"
hits = {str(h["song"]): h for h in json.loads((V / "shortlist.json").read_text(encoding="utf-8"))}

_sb, _mbh = {}, {}


def sb_has(canto, chapter, n):
    key = (canto, chapter)
    if key not in _sb:
        cover = set()
        for lab, _ in sb(canto, chapter):
            lo, _, hi = lab.replace("–", "-").partition("-")
            for i in range(int(lo), int(hi or lo) + 1):
                cover.add(i)
        _sb[key] = cover
    return n in _sb[key]


def mbh_ref(parva, ref):
    if parva not in _mbh:
        _mbh[parva] = {r: t for _, r, t in mbh_lines(parva)}
    t = _mbh[parva].get(ref)
    if t is None:
        sys.exit(f"Mahabharata ref not found: {ref}")
    return t


def sb_cell(e):
    return "; ".join(f"SB {c}.{ch}.{v}" for c, ch, v, g in e["sb"]) or "-"


def mbh_cell(e):
    out = []
    for p, adh, refs, g in e["mbh"]:
        out.append(f"{refs[0]}–{refs[-1]}" if len(refs) > 1 else refs[0])
    return "; ".join(out) or "-"


for eid, e in E.items():
    for c, ch, v, g in e["sb"]:
        lo, _, hi = v.partition("-")
        for n in range(int(lo), int(hi) + 1):
            if not sb_has(c, ch, n):
                sys.exit(f"Bhagavata verse missing: {c}.{ch}.{n} ({eid})")
    for p, adh, refs, g in e["mbh"]:
        for r in refs:
            mbh_ref(p, r)

out = [
    "# Krishna and Mahabharata episodes: verse-level references",
    "",
    "Generated by `scripts/build_krishna_verses.py` from `scripts/krishna_episodes.py`. Do not hand-edit.",
    "",
    "Bhagavata numbers follow vedabase.io (canto.chapter.verse). Mahabharata numbers are Critical Edition (BORI) line "
    "references from the GRETIL text, e.g. `6,023.021c` = parva 6, adhyaya 23, shloka 21, second half. A reference with "
    "`*` is a star passage: a variant not in the constituted text. Every number below was looked up and exists; the gists are mine.",
    "",
]
for eid, e in E.items():
    n = sum(1 for v in A_.values() if eid in v["eps"])
    out += [f"## {e['title']}  (`{eid}`, {n} songs)", ""]
    if e["sb"]:
        out.append("**Bhagavata Purana**")
        out.append("")
        for c, ch, v, g in e["sb"]:
            out.append(f"- SB {c}.{ch}.{v}: {g}")
        out.append("")
    if e["mbh"]:
        out.append("**Mahabharata (Critical Edition)**")
        out.append("")
        for p, adh, refs, g in e["mbh"]:
            out.append(f"- {refs[0]}" + (f" … {refs[-1]}" if len(refs) > 1 else "") + f": {g}")
            for r in refs:
                out.append(f"    - `{r}` {mbh_ref(p, r)}")
        out.append("")
    if not e["sb"] and not e["mbh"]:
        out += ["No verse reference.", ""]
    if e["note"]:
        out += [f"Note: {e['note']}", ""]
    songs = sorted((s for s, v in A_.items() if eid in v["eps"]), key=int)
    out += ["Songs: " + (", ".join(songs) if songs else "none"), ""]
(V / "krishna-episodes.md").write_text("\n".join(out), encoding="utf-8")

rows = [
    "# Krishna and Mahabharata songs: verse-level references",
    "",
    "Generated. See `krishna-episodes.md` for what each reference says. Conf h/m/l is the match between the song's line "
    "and the episode, not about the numbers.",
    "",
    "| Song | Line (with previous line) | Episode(s) | Bhagavata | Mahabharata (CE) | Conf | Note |",
    "|---|---|---|---|---|---|---|",
]
for sid in sorted(A_, key=int):
    h = hits[sid]
    v = A_[sid]
    es = [E[x] for x in v["eps"]]
    rows.append(
        f"| {sid} {h['title']} | {h['prev_line']} / **{h['line']}** | "
        + ", ".join(e["title"] for e in es)
        + " | "
        + "<br>".join(sb_cell(e) for e in es if e["sb"] or not e["mbh"])
        + " | "
        + "<br>".join(mbh_cell(e) for e in es if e["mbh"])
        + f" | {v['conf']} | {v['note']} |"
    )
(V / "krishna-verses.md").write_text("\n".join(rows) + "\n", encoding="utf-8")

smap = {}
for line in (V / "song-story-map.txt").read_text(encoding="utf-8").splitlines():
    if line.strip() and not line.startswith("#"):
        sid, slugs, _, _ = line.split("|")
        smap[sid] = slugs.split(",")
kr = {s for s, sl in smap.items() if any(x.startswith(("krishna-", "mbh-")) for x in sl)}
print(len(E), "episodes;", len(A_), "songs assigned; Krishna/MBh songs in the map without an episode:", sorted(kr - set(A_), key=int))
