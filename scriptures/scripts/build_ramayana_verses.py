"""Build vishnu/ramayana-episodes.md and vishnu/ramayana-verses.md from ramayana_episodes.py.

Every cited Kamba verse number is looked up in the Tamil Wikisource text (cached) and quoted; the build fails
if a number does not exist, so a typo cannot slip through. Valmiki sarga/shloka numbers are hand-entered from
valmikiramayan.net pages read in session 1 (see SOURCES.md).
Run:  python -I scriptures/scripts/build_ramayana_verses.py   (needs network the first time)
"""
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.stdout.reconfigure(encoding="utf-8")
from find_kamba import verses  # noqa: E402
from ramayana_episodes import A_, E  # noqa: E402

V = Path(__file__).resolve().parent.parent / "vishnu"
hits = {str(h["song"]): h for h in json.loads((V / "shortlist.json").read_text(encoding="utf-8"))}

_cache = {}


def kverse(kandam, padalam, n):
    key = (kandam, padalam)
    if key not in _cache:
        _cache[key] = {num: t for num, _, t in verses(kandam, padalam)}
    d = _cache[key]
    if str(n) not in d:
        sys.exit(f"Kamba verse not found: {padalam} {n}")
    return d[str(n)]


def pname(p):
    return p.replace("_", " ")


def kamba_cell(e):
    parts = []
    for kandam, pad, nums in e["kamba"]:
        if nums:
            parts.append(f"{pname(pad)} {', '.join(map(str, nums))}")
        else:
            parts.append(f"{pname(pad)} (verse not pinned)")
    return "; ".join(parts) or "not located"


def valmiki_cell(e):
    return "; ".join(f"{k} {r}" for k, s, r, g in e["valmiki"]) or "not located"


# ---- episodes file
out = [
    "# Ramayana episodes: verse-level references",
    "",
    "Generated by `scripts/build_ramayana_verses.py` from `scripts/ramayana_episodes.py`. Do not hand-edit.",
    "",
    "Valmiki = `Kanda sarga.shloka` as numbered on valmikiramayan.net. Kamba = padalam name + verse number as numbered "
    "on Tamil Wikisource (numbers restart in each padalam; this is not the Kamban Kazhagam running number). "
    "Every Kamba verse number below was looked up in the text and is quoted. Where a verse is the first of a "
    "Wikisource section (e.g. 337 'Kumbakarna loses his arm'), it marks where that passage begins, not each line of it.",
    "",
]
for eid, e in E.items():
    n = sum(1 for v in A_.values() if eid in v["eps"])
    out += [f"## {e['title']}  (`{eid}`, {n} songs)", ""]
    out.append("**Valmiki Ramayana**")
    out.append("")
    if e["valmiki"]:
        for k, s, r, g in e["valmiki"]:
            out.append(f"- {k} {r}: {g}")
    else:
        out.append("- not located")
    out += ["", "**Kamba Ramayanam**", ""]
    if e["kamba"]:
        for kandam, pad, nums in e["kamba"]:
            if not nums:
                out.append(f"- {pname(pad)} ({kandam.replace('_', ' ')}): verse not pinned yet")
            for nn in nums:
                t = kverse(kandam, pad, nn)
                out.append(f"- {pname(pad)} {nn}: {t[:150]}{'…' if len(t) > 150 else ''}")
    else:
        out.append("- not located")
    if e["note"]:
        out += ["", f"Note: {e['note']}"]
    songs = sorted((s for s, v in A_.items() if eid in v["eps"]), key=int)
    out += ["", "Songs: " + (", ".join(songs) if songs else "none"), ""]
(V / "ramayana-episodes.md").write_text("\n".join(out), encoding="utf-8")

# ---- per-song file
rows = [
    "# Ramayana songs: verse-level references",
    "",
    "Generated; see `ramayana-episodes.md` for what each verse says. Confidence h/m/l is about the match between the "
    "song's line and the episode, not about the verse numbers.",
    "",
    "| Song | Line (with previous line) | Episode(s) | Valmiki | Kamba (padalam verse) | Conf | Note |",
    "|---|---|---|---|---|---|---|",
]
for sid in sorted(A_, key=int):
    h = hits[sid]
    v = A_[sid]
    es = [E[x] for x in v["eps"]]
    rows.append(
        f"| {sid} {h['title']} | {h['prev_line']} / **{h['line']}** | "
        + ", ".join(e["title"] for e in es)
        + " | "
        + "<br>".join(valmiki_cell(e) for e in es)
        + " | "
        + "<br>".join(kamba_cell(e) for e in es)
        + f" | {v['conf']} | {v['note']} |"
    )
(V / "ramayana-verses.md").write_text("\n".join(rows) + "\n", encoding="utf-8")

# coverage check against the story map
smap = {}
for line in (V / "song-story-map.txt").read_text(encoding="utf-8").splitlines():
    if line.strip() and not line.startswith("#"):
        sid, slugs, _, _ = line.split("|")
        smap[sid] = slugs.split(",")
rama_songs = {s for s, sl in smap.items() if any(x.startswith("ram-") for x in sl)}
missing = sorted(rama_songs - set(A_), key=int)
print(len(E), "episodes;", len(A_), "songs assigned; Rama songs in the story map without an episode:", missing)
